begin;
do $$
declare code text:=encode(extensions.gen_random_bytes(32),'hex');pass text:=encode(extensions.gen_random_bytes(24),'hex');r jsonb;old_session text;recovery text;i integer;blocked boolean:=false;
begin
 update verdelia_private.account set password_hash=null,activation_hash=encode(extensions.digest(code,'sha256'),'hex'),activation_expires=now()+interval '1 hour',failed=0,locked_until=null;
 r:=public.verdelia_login('activate',jsonb_build_object('token',code,'password','short'));
 assert r ? 'error','Weak password accepted';
 r:=public.verdelia_login('activate',jsonb_build_object('token',code,'password',pass));
 assert r ? 'session','Activation failed';old_session:=r->>'session';recovery:=r->>'recovery_code';
 perform verdelia_private.require_admin(old_session);
 r:=public.verdelia_login('activate',jsonb_build_object('token',code,'password',pass));
 assert r ? 'error','Activation token reused';
 for i in 1..5 loop perform public.verdelia_login('login',jsonb_build_object('username','verdelia','password','incorrect'));end loop;
 r:=public.verdelia_login('login',jsonb_build_object('username','verdelia','password',pass));
 assert r ? 'error','Login lock not applied';
 r:=public.verdelia_login('recover',jsonb_build_object('token',recovery,'password',pass));
 assert r ? 'session','Recovery failed';
 begin perform verdelia_private.require_admin(old_session);exception when insufficient_privilege then blocked:=true;end;
 assert blocked,'Recovery did not invalidate old sessions';
 old_session:=r->>'session';
 r:=public.verdelia_login('recover',jsonb_build_object('token',recovery,'password',pass));
 assert r ? 'error','Old recovery token reused';
 perform public.verdelia_login('logout',jsonb_build_object('session',old_session));blocked:=false;
 begin perform verdelia_private.require_admin(old_session);exception when insufficient_privilege then blocked:=true;end;
 assert blocked,'Logout did not invalidate session';
 assert not has_table_privilege('anon','verdelia_private.account','select'),'Anonymous account read';
 assert not has_table_privilege('authenticated','verdelia_private.sales','select'),'Authenticated Invicto user can read Verdelia';
end $$;
select 'PASS: activation, password policy, reuse, lockout, recovery, logout and private tables' result;
rollback;
